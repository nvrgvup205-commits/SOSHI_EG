export const translations: Record<Language, Record<string, string>> = { ar, en, ru };

export function t(key: string, lang: Language): string {
  return translations[lang][key] || translations.en[key] || key;
}

export function getProductName(product: { name_ar: string; name_en: string; name_ru: string }, lang: Language) {
  if (lang === 'ar') return product.name_ar;
  if (lang === 'ru') return product.name_ru;
  return product.name_en;
}

export function getProductDescription(
  product: { description_ar: string | null; description_en: string | null; description_ru: string | null },
  lang: Language,
) {
  if (lang === 'ar') return product.description_ar;
  if (lang === 'ru') return product.description_ru;
  return product.description_en;
}

export function localizedName(
  item: { name_ar: string; name_en: string; name_ru: string },
  lang: Language,
) {
  return getProductName(item, lang);
}
